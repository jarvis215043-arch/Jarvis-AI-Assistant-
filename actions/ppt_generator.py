"""
actions/ppt_generator.py — Generates a PowerPoint (.pptx) on a topic and opens it.
Runs in the background so JARVIS stays responsive; announces completion on its
own. Uses core/text_generation.py, which tries Gemini first and falls back to
a local LLM (Ollama) if Gemini is unreachable, with tolerant JSON parsing for
smaller local models.
"""
import importlib.util
import json
import re
import subprocess
import sys
import threading
import time
from pathlib import Path

from pptx import Presentation


def _base_dir() -> Path:
    if getattr(sys, "frozen", False):
        return Path(sys.executable).parent
    return Path(__file__).resolve().parent.parent


def _config() -> dict:
    try:
        return json.loads((_base_dir() / "config" / "api_keys.json").read_text(encoding="utf-8"))
    except Exception:
        return {}


def _get_os() -> str:
    return _config().get("os_system", "windows").lower()


def _output_dir() -> Path:
    out = _base_dir() / "generated_ppts"
    out.mkdir(parents=True, exist_ok=True)
    return out


def _open_file(path: Path) -> None:
    os_name = _get_os()
    try:
        if os_name == "windows":
            import os
            os.startfile(str(path))
        elif os_name == "mac":
            subprocess.run(["open", str(path)], check=False)
        else:
            subprocess.run(["xdg-open", str(path)], check=False)
    except Exception as e:
        print(f"[PPTGenerator] ⚠️ Could not auto-open {path}: {e}")


def _say(player, text: str) -> None:
    if player and hasattr(player, "request_say"):
        try:
            player.request_say(text)
        except Exception:
            pass


def _get_text_generation_module():
    key = "jarvis_ext_text_generation"
    if key in sys.modules:
        return sys.modules[key]
    path = _base_dir() / "core" / "text_generation.py"
    spec = importlib.util.spec_from_file_location(key, str(path))
    mod = importlib.util.module_from_spec(spec)
    sys.modules[key] = mod
    spec.loader.exec_module(mod)
    return mod


_OUTLINE_SYSTEM = (
    "You output ONLY valid JSON, nothing else — no markdown fences, no commentary. "
    'Format: {"title": "<deck title>", "slides": [{"title": "<slide title>", '
    '"bullets": ["<point>", "<point>", "<point>"]}, ...]}'
)


def _get_outline(topic: str, num_slides: int) -> dict:
    tg = _get_text_generation_module()
    prompt = (
        f"{_OUTLINE_SYSTEM}\n\n"
        f"Create an outline for a {num_slides}-slide presentation on: {topic}. "
        f"Each slide needs a short title and 3-4 concise bullet points."
    )
    data = tg.generate_json(prompt)
    if "title" not in data or "slides" not in data:
        raise ValueError("Model returned an unexpected outline shape.")
    return data


def _build_pptx(outline: dict) -> Path:
    prs = Presentation()

    title_slide = prs.slides.add_slide(prs.slide_layouts[0])
    title_slide.shapes.title.text = outline["title"]
    if len(title_slide.placeholders) > 1:
        title_slide.placeholders[1].text = "Generated by JARVIS"

    bullet_layout = prs.slide_layouts[1]
    for slide_data in outline["slides"]:
        slide = prs.slides.add_slide(bullet_layout)
        slide.shapes.title.text = slide_data.get("title", "")
        body = slide.placeholders[1].text_frame
        body.clear()
        for i, bullet in enumerate(slide_data.get("bullets", [])):
            p = body.paragraphs[0] if i == 0 else body.add_paragraph()
            p.text = str(bullet)

    safe_name = re.sub(r"[^\w\-]+", "_", outline["title"]).strip("_")[:50] or "presentation"
    path = _output_dir() / f"{safe_name}_{int(time.time())}.pptx"
    prs.save(str(path))
    return path


def _work(topic: str, num_slides: int, player, session_memory):
    try:
        outline = _get_outline(topic, num_slides)
        path    = _build_pptx(outline)
    except Exception as e:
        err = f"Sir, I couldn't build that presentation: {e}"
        _log(err, player)
        _say(player, err)
        return

    _open_file(path)
    done = f"Your presentation on {topic} is ready, sir — {len(outline['slides'])} slides, and it's open now."
    _log(done, player)
    _say(player, done)
    if session_memory:
        try:
            session_memory.set_last_search(query=f"generate ppt: {topic}", response=done)
        except Exception:
            pass


def generate_ppt(parameters: dict, player=None, session_memory=None) -> str:
    params     = parameters or {}
    topic      = (params.get("topic") or "").strip()
    num_slides = max(3, min(int(params.get("num_slides") or 5), 12))

    if not topic:
        msg = "Sir, what should the presentation be about?"
        _log(msg, player)
        return msg

    threading.Thread(target=_work, args=(topic, num_slides, player, session_memory), daemon=True).start()

    msg = f"On it, sir — building your {num_slides}-slide presentation on {topic} now. I'll let you know when it's ready."
    _log(msg, player)
    return msg


def _log(message: str, player=None) -> None:
    print(f"[PPTGenerator] {message}")
    if player:
        try:
            player.write_log(f"JARVIS: {message}")
        except Exception:
            pass


TOOL = {
    "name": "generate_ppt",
    "description": (
        "Creates a PowerPoint presentation on a given topic in the background and "
        "opens it when ready. Returns immediately with an acknowledgment — the "
        "actual file arrives a bit later as a follow-up, spoken on its own."
    ),
    "parameters": {
        "type": "OBJECT",
        "properties": {
            "topic": {"type": "STRING", "description": "Topic or title for the presentation"},
            "num_slides": {"type": "NUMBER", "description": "Number of content slides (default 5)"}
        },
        "required": ["topic"]
    },
    "handler": generate_ppt,
}